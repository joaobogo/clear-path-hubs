/**
 * One operator statement that gives every match the pipeline could not score
 * the admin task the rule promises ("a candidate the pipeline cannot score
 * always has an open admin task"), for matches parked before that rule ran
 * or by a path that skipped it.
 *
 * The task wording is not written twice: each branch of the statement is
 * candidateReviewTask() rendered with placeholders for the candidate, the
 * role and the stored error message, so the backfilled task reads exactly as
 * the pipeline's would. The checked-in copy is
 * scripts/offline-rescore/open-unscored-tasks.sql, and a test keeps it equal
 * to unscoredTaskBackfillSql().
 *
 * The statement only inserts tasks. It never touches scores, eligibility,
 * admin_status, client_visibility or stage, and a task row sends nothing to
 * anyone (reminder_policy stays at its 'none' default).
 */
import {
  HIGH_PRIORITY_REVIEW_CODES,
  REVIEW_TASK_CODES,
  candidateReviewTask,
} from "./unscored-review";

/** States in which a match has no usable score and needs a person. */
export const BACKFILL_UNSCORED_STATES = [
  "failed",
  "ocr_required",
  "provider_blocked",
  "manual_review_required",
] as const;

/** A piece of task text: literal words, or a value read from the match. */
export type TemplatePart = { text: string } | { field: "who" | "role" | "detail" };

export type TaskTemplate = {
  /** null: every code without a branch of its own. */
  code: string | null;
  title: TemplatePart[];
  description: TemplatePart[];
  priority: "normal" | "high";
};

const WHO = "\uE000W";
const ROLE = "\uE000R";
const DETAIL = "\uE000D";
const OTHER = "\uE000other";

function parts(rendered: string): TemplatePart[] {
  const s = rendered.replace(` for ${ROLE}`, ROLE).replace(` ${DETAIL}`, DETAIL);
  const out: TemplatePart[] = [];
  for (const piece of s.split(/(\uE000[WRD])/)) {
    if (piece === WHO) out.push({ field: "who" });
    else if (piece === ROLE) out.push({ field: "role" });
    else if (piece === DETAIL) out.push({ field: "detail" });
    else if (piece) out.push({ text: piece });
  }
  if (out.some((p) => "text" in p && p.text.includes("\uE000"))) {
    throw new Error("unscored backfill: a placeholder was not replaced");
  }
  return out;
}

/** candidateReviewTask() for each code, with placeholders for the match's own values. */
export function taskTemplates(): TaskTemplate[] {
  const codes = [...new Set([...REVIEW_TASK_CODES, ...HIGH_PRIORITY_REVIEW_CODES])];
  return [...codes, null].map((code) => {
    const t = candidateReviewTask({
      code: code ?? OTHER,
      message: DETAIL,
      candidateName: WHO,
      positionTitle: ROLE,
    });
    return { code, title: parts(t.title), description: parts(t.description), priority: t.priority };
  });
}

/** Renders a template as the statement does, for tests and previews. */
export function renderTemplate(
  p: TemplatePart[],
  v: { name?: string | null; title?: string | null; message?: string | null },
): string {
  return p
    .map((x) => {
      if ("text" in x) return x.text;
      if (x.field === "who") return v.name?.trim() || "Candidate";
      if (x.field === "role") return v.title?.trim() ? ` for ${v.title.trim()}` : "";
      return v.message?.trim() ? ` ${v.message.trim()}` : "";
    })
    .join("");
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const COLUMN = { who: "u.who", role: "u.role", detail: "u.detail" } as const;
const concat = (p: TemplatePart[]) =>
  p.map((x) => ("text" in x ? lit(x.text) : COLUMN[x.field])).join(" || ");

function caseOver(templates: TaskTemplate[], pick: (t: TaskTemplate) => string): string {
  const other = templates.find((t) => t.code === null)!;
  const branches = templates
    .filter((t) => t.code !== null)
    .map((t) => `    WHEN ${lit(t.code!)} THEN ${pick(t)}`);
  return `CASE u.code\n${branches.join("\n")}\n    ELSE ${pick(other)}\n  END`;
}

export function unscoredTaskBackfillSql(): string {
  const templates = taskTemplates();
  const high = templates
    .filter((t) => t.priority === "high" && t.code !== null)
    .map((t) => lit(t.code!));
  const states = BACKFILL_UNSCORED_STATES.map(lit).join(", ");
  return `-- Generated by unscoredTaskBackfillSql() in src/lib/cv/unscored-backfill.ts;
-- a test keeps this copy equal to it. Do not edit by hand.
--
-- Opens one candidate_review task for every match that has no current score,
-- is parked in an unscored state, is not a test record, is on a role that is
-- not filled, closed or archived, and has no open candidate_review task from
-- any source. The wording is the pipeline's own (candidateReviewTask).
--
-- Idempotent: a second run inserts nothing. It only inserts tasks: no score,
-- eligibility, admin_status, client_visibility or stage changes, and a task
-- row sends nothing to anyone. RETURNING lists what was opened.
--
-- Preview first by running the SELECT inside "unscored" on its own.
WITH unscored AS (
  SELECT m.id, m.organization_id, m.position_id, m.candidate_profile_id,
    m.processing_state::text AS final_state,
    coalesce(nullif(btrim(split_part(coalesce(m.processing_error_code, m.processing_state::text), ':', 1)), ''), 'unknown') AS code,
    coalesce(nullif(btrim(cp.full_name), ''), 'Candidate') AS who,
    coalesce(' for ' || nullif(btrim(p.title), ''), '') AS role,
    coalesce(' ' || nullif(btrim(m.processing_error_message), ''), '') AS detail
  FROM candidate_matches m
  LEFT JOIN candidate_profiles cp ON cp.id = m.candidate_profile_id
  LEFT JOIN positions p ON p.id = m.position_id
  WHERE m.current_score_run_id IS NULL
    AND m.processing_state::text IN (${states})
    AND m.is_test_record = false
    AND coalesce(p.status::text, '') NOT IN ('filled', 'closed', 'archived')
    AND NOT EXISTS (
      SELECT 1 FROM tasks t
      WHERE t.candidate_match_id = m.id AND t.task_type = 'candidate_review'
        AND t.status IN ('open', 'in_progress') AND t.deleted_at IS NULL
    )
)
INSERT INTO tasks (organization_id, position_id, candidate_match_id, candidate_profile_id, task_type, title, description, priority, status, metadata)
SELECT u.organization_id, u.position_id, u.id, u.candidate_profile_id, 'candidate_review',
  ${caseOver(templates, (t) => concat(t.title))},
  ${caseOver(templates, (t) => concat(t.description))},
  (CASE WHEN u.code IN (${high.join(", ")}) THEN 'high' ELSE 'normal' END)::task_priority,
  'open',
  jsonb_build_object('source', 'unscored_backfill', 'reason', u.code, 'final_state', u.final_state)
FROM unscored u
RETURNING id, candidate_match_id, title;
`;
}
